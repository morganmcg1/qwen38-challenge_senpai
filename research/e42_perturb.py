#!/usr/bin/env python3
"""E42 - inject a bit-exact, width-gated regression into the affine4/g64 QMV cells.

Why this exists
---------------
psi (the quantised-matvec share of the candidate leg) has never been measured.
Every attempt failed the same way: the effect of interest is ~0.06 % against a
paired-E2E floor of 0.417 % normal / 0.632 % exact at n=4 (`research/e39_mde.py`).
So E42 does not measure an improvement. It injects a large, *deliberate*
slowdown whose kernel-level magnitude is measured on the shapes-only curve, and
divides:

    psi_effective = (measured leg slowdown) / (measured kernel slowdown)

Bit-exactness by construction, not by luck
------------------------------------------
The perturbation runs the *entire* accumulation region `E42_PASSES` extra times.
Each pass re-initialises the accumulators and then executes the unchanged K loop
in the unchanged order, so the accumulators after the final pass hold exactly the
bits the base kernel would have held. Nothing is reassociated, no lane
membership moves, `simd_sum` and the store are untouched, and the write happens
once, after the last pass. Compare the alternatives that were rejected: `+ 0.0f *`
does not survive fast-math, and any partial/fused second pass changes the FP
expression tree - reassociation on the verify path is a ranked-measured
rejection class (`research/crossrow-closure.md:31-38`).

Because the earlier passes are dead by construction, a compiler is *entitled* to
delete them. That is a measurement risk, not a correctness risk, and it is
checked two ways before any leg is timed: statically with
`research/e42_air_probe.metal` + `research/air_kernel_stats.py` (device_loads and
float_ops must scale with the pass count), and dynamically on the shapes-only
curve (the treated widths must actually slow down).

NOTHING HERE SHIPS. Every arm is a regression; the branch ends with the two
twins byte-identical to BASE_SHA.

Usage
-----
    research/e42_perturb.py --arm p2 --level 1     # patch worktree, twins locked
    research/e42_perturb.py --arm p6 --level 2
    research/e42_perturb.py --arm m1 --level 1
    research/e42_perturb.py --revert               # restore both twins from base
    research/e42_perturb.py --self-test            # no worktree writes
"""

