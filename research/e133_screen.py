def probe_ladder(out: dict, stages) -> dict:
    """F4.4. Best clearing cell at every probe fraction, per stage.

    The probe fraction is the lever on the `P` component of the base miss, and
    the byte ladder hides it because a cell's bytes barely move with `p` while
    its stage-B byte count moves a lot. This table puts the two on one axis.
    """
    table: dict = {}
    for stage_a in stages:
        rows: dict = {}
        fractions = sorted({c["probe_fraction"] for c in out["cells"]
                            if c["stage_a"] == stage_a})
        for p in fractions:
            arms = [c for c in out["cells"] if c["stage_a"] == stage_a
                    and c["probe_fraction"] == p]
            ok = [c for c in arms if c["passes_t0"] and c["passes_t0b"]]
            best = max(ok, key=lambda c: c["predicted_pct_absolute"],
                       default=None)
            rows[f"{p:g}"] = {
                "cells": len(arms),
                "cells_passing_both": len(ok),
                "max_byte_rate_gain_pct": max(c["pct_head_share_7"] for c in arms),
                "min_net_miss_worst_gating":
                    min(c["net_miss_worst_gating"] for c in arms),
                "best_arm": best["arm"] if best else None,
                "best_bytes_per_row": best["bytes_per_row"] if best else None,
                "best_predicted_pct":
                    best["predicted_pct_absolute"] if best else None,
                "best_predicted_pct_incremental":
                    best["predicted_pct_gating"] if best else None,
                "best_gross_pct": best["pct_head_share_7"] if best else None,
                "best_net_miss": best["net_miss_worst_gating"] if best else None,
                "best_m_absolute": best["m_absolute_worst_gating"] if best else None,
                "best_m_incremental":
                    best["m_incremental_worst_gating"] if best else None,
                "best_recall": best["recall_worst_gating"] if best else None,
            }
        table[stage_a] = rows
    return table


def byte_ladder(out: dict, stages) -> dict:
    """Best clearing cell at every per-row byte size, per stage.

    F3.2's kill rule asks whether ANY cell clears at ANY byte size, and its
    selection rule asks for the cheapest one that does. Both questions are
    answered by one table, and the table also shows the thing neither rule
    anticipates: the byte-rate gain falls with size while the miss penalty
    falls faster, so the best-priced size is interior, not the cheapest.
    """
    table: dict = {}
    for stage_a in stages:
        rows: dict = {}
        sizes = sorted({c["bytes_per_row"] for c in out["cells"]
                        if c["stage_a"] == stage_a})
        for size in sizes:
            arms = [c for c in out["cells"] if c["stage_a"] == stage_a
                    and c["bytes_per_row"] == size]
            ok = [c for c in arms if c["passes_t0"] and c["passes_t0b"]]
            best = max(ok, key=lambda c: c["predicted_pct_absolute"], default=None)
            rows[str(size)] = {
                "cells": len(arms),
                "cells_passing_both": len(ok),
                "max_byte_rate_gain_pct": max(c["pct_head_share_7"] for c in arms),
                "min_net_miss_worst_gating":
                    min(c["net_miss_worst_gating"] for c in arms),
                "best_arm": best["arm"] if best else None,
                "best_family": best["family"] if best else None,
                "best_predicted_pct":
                    best["predicted_pct_absolute"] if best else None,
                "best_predicted_pct_incremental":
                    best["predicted_pct_gating"] if best else None,
                "best_predicted_pct_pooled":
                    best["predicted_pct_pooled"] if best else None,
                "best_predicted_pct_raw_miss":
                    best["predicted_pct_raw_miss"] if best else None,
                "best_net_miss": best["net_miss_worst_gating"] if best else None,
                "best_recall": best["recall_worst_gating"] if best else None,
            }
        table[stage_a] = rows
    return table


def sign_test(wins: int, losses: int) -> float:
    """Two-sided exact sign test. Ties carry no information and are dropped."""
    n = wins + losses
    if not n:
        return 1.0
    k = min(wins, losses)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / (1 << n)
    return min(1.0, 2.0 * tail)


def whitening_paired(out: dict) -> dict:
    """F3.3, decided as a paired comparison instead of a leaderboard read.

    `wlowrank` and `qlowrank` differ only in the int8 grid, so every cell has
    an exact twin at the same stage, rank, survivor width and probe fraction.
    Comparing the twins removes all of the between-cell variation and leaves
    the quantization change on its own.
    """
    def key(c):
        return (c["stage_a"], c["size"], c["survivors"], c["probe_fraction"])

    plain = {key(c): c for c in out["cells"] if c["family"] == "qlowrank"}
    white = {key(c): c for c in out["cells"] if c["family"] == "wlowrank"}
    shared = sorted(set(plain) & set(white))
    report: dict = {"paired_cells": len(shared), "fields": {}}
    for field, better in (("net_miss_worst_gating", "lower"),
                          ("m_incremental_worst_gating", "lower"),
                          ("recall_worst_gating", "higher"),
                          ("predicted_pct_absolute", "higher"),
                          ("predicted_pct_gating", "higher")):
        wins = ties = losses = 0
        total = 0.0
        for k in shared:
            delta = white[k][field] - plain[k][field]
            total += delta
            if abs(delta) < 1e-12:
                ties += 1
            elif (delta < 0) == (better == "lower"):
                wins += 1
            else:
                losses += 1
        report["fields"][field] = {
            "better": better, "whitened_wins": wins, "ties": ties,
            "whitened_losses": losses,
            "mean_delta_whitened_minus_plain": total / len(shared) if shared else None,
            "sign_test_p": sign_test(wins, losses),
        }
    report["t0_verdict_flips"] = sum(
        1 for k in shared if plain[k]["passes_t0"] != white[k]["passes_t0"])
    report["t0b_verdict_flips"] = sum(
        1 for k in shared if plain[k]["passes_t0b"] != white[k]["passes_t0b"])
    for tag, side in (("plain", plain), ("whitened", white)):
        ok = [side[k] for k in shared
              if side[k]["passes_t0"] and side[k]["passes_t0b"]]
        best = max(ok, key=lambda c: c["predicted_pct_gating"], default=None)
        report[f"best_clearing_{tag}_arm"] = best["arm"] if best else None
        report[f"best_clearing_{tag}_predicted_pct"] = (
            best["predicted_pct_gating"] if best else None)
    return report


def spectrum_vs_miss(out: dict, stages) -> dict:
    """Held-out captured query energy at rank `r`, beside the best empirical
    net miss any rank-`r` query-fitted cell reaches.

    Captured energy is the quantity a spectral argument would use to predict
    the sketch error. Putting it next to the measured miss shows directly
    whether that argument holds at the ranks this screen can afford.
    """
    energy = out.get("query_basis", {}).get("energy_kept", {})
    held = {
        "captured_beagle": energy.get("fit_min_carriers/test_beagle", {}),
        "captured_min_carriers": energy.get("fit_beagle/test_min_carriers", {}),
        "captured_essays_bacon":
            energy.get(f"fit_{BACON_HOLDOUT_FIT}/test_{BACON_SEED}", {}),
    }
    table: dict = {}
    for stage_a in stages:
        rows: dict = {}
        for r in (64, 128, 256, 512, 1024):
            arms = [c for c in out["cells"]
                    if c["stage_a"] == stage_a and c["size"] == r
                    and c["family"] in QUERY_FIT_FAMILIES]
            best = min(arms, key=lambda c: c["net_miss_worst_gating"],
                       default=None)
            rows[str(r)] = {
                **{k: v.get(str(r)) for k, v in held.items()},
                "cells": len(arms),
                "best_arm": best["arm"] if best else None,
                "best_net_miss": best["net_miss_worst_gating"] if best else None,
                "best_recall": best["recall_worst_gating"] if best else None,
                "best_bytes_per_row": best["bytes_per_row"] if best else None,
            }
        table[stage_a] = rows
    return table


def sweep_group(screen: Screen, sketches: list[SketchSet], args,
                stages, fractions, widths, cells: dict[tuple, Cell],
                base_cell: Cell, structural_cell: Cell,
                accept: dict[str, list[int]], collect_base: bool) -> int:
    """One pass over the corpus with the sketches currently resident.

    Wide cells hold `98,336 x size` float32 row codes, so a 15-family sweep at
    `S = 8192` or `r = 1024` does not fit. The corpus pass is cheap relative to
    building those codes, so the sweep runs in groups and accumulates into one
    shared `cells` map. The base and acceptance counters are collected once.
    """
    n = 0
    t0 = time.time()
    for seed, stratum, x, proposal, reference, accepted, live in chunks(
            args.batch, args.limit):
        watch = seed if seed in WATCH_STRATA else None
        # F3.1. The hardest carrier is scored a second time with the fold that
        # excluded it, under its own non-gating stratum name.
        passes = [(stratum, watch)]
        if seed == BACON_SEED:
            passes.append((BACON_HOLDOUT, None))
        f = screen.front(x)
        base_miss, base_compact, structural = screen.shipped(f)
        base_vocab = np.asarray(H.compact_to_vocab(base_compact))
        if collect_base:
            falses = np.zeros_like(base_miss)
            for record, w in passes:
                base_cell.add(record, base_miss, base_miss, falses, ~falses,
                              ~falses, ~falses, watch=w)
                structural_cell.add(record, structural, structural, falses,
                                    ~falses, ~falses, ~falses, watch=w)
            for key in {k for record, w in passes for k in (record, w) if k}:
                slot = accept.setdefault(key, [0, 0, 0, 0])
                slot[0] += int(proposal.size)
                slot[1] += int((base_vocab == reference).sum())
                slot[2] += int((base_vocab == proposal).sum())
                slot[3] += int(accepted.sum())
        for entry in sketches:
            for record, w in passes:
                sketch = entry.pick(record)
                state = sketch_state(screen, sketch, f, x)
                for stage_a in stages:
                    run_arm(screen, sketch, f, state, fractions, widths,
                            base_miss, base_compact, record, reference,
                            base_vocab, live, cells, stage_a, w)
                del state
        n += f["b"]
        if n % (args.batch * 20) == 0:
            print(f"    {n} samples  {time.time() - t0:.0f}s", flush=True)
    return n


def cmd_screen(args) -> None:
    index = Index(Path(args.index))
    screen = Screen(index)
    families = parse_families(args.families)
    widths = [int(v) for v in args.widths.split(",")]
    fractions = [float(v) for v in args.probes.split(",")]
    stages = [v for v in args.stage_a.split(",") if v]
    group = args.group_size if args.group_size > 0 else len(families)

    cells: dict[tuple, Cell] = {}
    base_cell = Cell()
    structural_cell = Cell()
    accept: dict[str, list[int]] = {}
    meta: dict[str, SketchSet] = {}
    query_report: dict = {}
    n = 0
    t0 = time.time()
    for start in range(0, len(families), group):
        block = families[start: start + group]
        print(f"\n-- group {start // group + 1}: "
              + ",".join(f"{f}{s}" for f, s in block), flush=True)
        sketches, report = build_sketches(screen, block)
        query_report = report or query_report
        got = sweep_group(screen, sketches, args, stages, fractions, widths,
                          cells, base_cell, structural_cell, accept,
                          collect_base=(start == 0))
        n = n or got
        for entry in sketches:
            meta[entry.key] = SketchMeta(entry)
        del sketches

    p_by_stratum = {k: (v[1] / v[0] if v[0] else float("nan"))
                    for k, v in accept.items()}
    real = {k: v for k, v in accept.items() if k in ALL_STRATA}
    aligned = sum(v[0] for v in real.values())
    out = {
        "samples": n,
        "base_sha": args.base_sha,
        "wall_seconds": time.time() - t0,
        "p_head_step_accuracy": (sum(v[1] for v in real.values()) / aligned
                                 if aligned else float("nan")),
        "p_head_step_accuracy_by_stratum": p_by_stratum,
        # The emitted-token rate, which is strictly below the row match rate
        # because a round discards every row after its first rejection.
        "p_row_accepted": (sum(v[3] for v in real.values()) / aligned
                           if aligned else float("nan")),
        "p_row_accepted_by_stratum": {
            k: (v[3] / v[0] if v[0] else float("nan"))
            for k, v in accept.items()},
        "offline_shipped_chain_reproduces_runtime":
            (sum(v[2] for v in real.values()) / aligned
             if aligned else float("nan")),
        "shipped": summarize("shipped", base_cell, price(0), {}, p_by_stratum),
        "shipped_structural_proxy": summarize(
            "shipped-structural", structural_cell, price(0), {}, p_by_stratum),
        "query_basis": query_report,
        "cells": [],
    }
    shipped_bytes = shipped_stage_bytes()
    tags = {"sketch": "", "affine2": "-hybridA", "nocentroid": "-nocentroid"}
    for (key, stage_a, n_keep, p), cell in cells.items():
        sketch = meta[key]
        # F4.3. At `p = 1` the leaf ordering cannot change which rows are
        # scored, so the sketch arm and the no-centroid arm have IDENTICAL
        # accuracy and differ only in bytes. The twin is a re-price of the same
        # measurement, never a second measurement.
        variants = [stage_a]
        if stage_a == "sketch" and p >= 1.0:
            variants.append("nocentroid")
        for variant in variants:
            arm_bytes = arm_stage_bytes(sketch.bytes_per_row, sketch.proj_bytes,
                                        n_keep, p, variant)
            out["cells"].append(summarize(
                f"{key}{tags[variant]}-N{n_keep}-p{p:g}", cell,
                price(shipped_bytes - arm_bytes),
                {"family": sketch.family, "size": sketch.size,
                 "stage_a": variant, "bytes_per_row": sketch.bytes_per_row,
                 "proj_bytes": sketch.proj_bytes, "survivors": n_keep,
                 "probe_fraction": p, "cross_fit": sketch.cross_fit,
                 "arm_stage_bytes": arm_bytes,
                 "shipped_stage_bytes": shipped_bytes},
                p_by_stratum))
    stages = [s for s in ("sketch", "affine2", "nocentroid")
              if any(c["stage_a"] == s for c in out["cells"])]
    out["cells"].sort(key=lambda c: -c["predicted_pct_absolute"])
    # F2.1. `hybridA` is a candidate, not a control. A stage-A kill must not
    # take it down with full C1, so each stage_a gets its own gate table and
    # its own selected cell.
    out["by_stage_a"] = {}
    for stage_a in stages:
        arms = [c for c in out["cells"] if c["stage_a"] == stage_a]
        ok = [c for c in arms if c["passes_t0"] and c["passes_t0b"]]
        # F4 advisor error 123. Select on predicted ranked value, priced on the
        # absolute miss. Bytes are an input to that price, never the selection
        # statistic. The cheapest clearing cell is still reported, because the
        # gap between the two is the cost of the rule that was withdrawn.
        best = max(ok, key=lambda c: c["predicted_pct_absolute"], default=None)
        cheap = min(ok, key=lambda c: (c["bytes_per_row"],
                                       -c["predicted_pct_absolute"]), default=None)
        out["by_stage_a"][stage_a] = {
            "label": {"sketch": "full C1", "affine2": "hybridA",
                      "nocentroid": "full C1, no centroid stage"}[stage_a],
            "cells": len(arms),
            "cells_passing_t0": sum(1 for c in arms if c["passes_t0"]),
            "cells_passing_t0b": sum(1 for c in arms if c["passes_t0b"]),
            "cells_passing_both": len(ok),
            "best_arm": best["arm"] if best else None,
            "best_predicted_pct": best["predicted_pct_absolute"] if best else 0.0,
            "best_predicted_pct_incremental":
                best["predicted_pct_gating"] if best else 0.0,
            "best_predicted_pct_pooled": best["predicted_pct_pooled"] if best else 0.0,
            "best_predicted_pct_raw_miss":
                best["predicted_pct_raw_miss"] if best else 0.0,
            "best_cell": best,
            "cheapest_arm": cheap["arm"] if cheap else None,
            "cheapest_bytes_per_row": cheap["bytes_per_row"] if cheap else None,
            "cheapest_predicted_pct":
                cheap["predicted_pct_absolute"] if cheap else 0.0,
            "cheapest_predicted_pct_realised":
                cheap["predicted_pct_gating"] if cheap else 0.0,
            "cheapest_predicted_pct_pooled":
                cheap["predicted_pct_pooled"] if cheap else 0.0,
            "cheapest_predicted_pct_raw_miss":
                cheap["predicted_pct_raw_miss"] if cheap else 0.0,
            "cheapest_cell": cheap,
            "byte_ceiling_searched": max((c["bytes_per_row"] for c in arms),
                                         default=0),
        }
        print(f"\n=== {stage_a}  ({out['by_stage_a'][stage_a]['label']})  "
              f"{len(ok)}/{len(arms)} cells clear T0 and T0b")
        print(CELL_HEADER)
        for cell in arms[: args.top]:
            print(fmt_cell(cell))
        if cheap:
            print(f"  cheapest clearing cell ({cheap['bytes_per_row']} B/row):")
            print(fmt_cell(cheap))
        else:
            print(f"  NO cell clears T0 and T0b up to "
                  f"{out['by_stage_a'][stage_a]['byte_ceiling_searched']} B/row")
    out["probe_ladder"] = probe_ladder(out, stages)
    for stage_a, rows in out["probe_ladder"].items():
        print(f"\n=== probe ladder  ({out['by_stage_a'][stage_a]['label']})")
        print(f"{'p':>6s}{'cells':>7s}{'clear':>7s}{'maxGain%':>10s}"
              f"{'minNet':>11s}{'bestB/row':>11s}{'bestGross%':>12s}"
              f"{'bestPredABS':>13s}{'bestPredF':>11s}   best clearing arm")
        for p, row in sorted(rows.items(), key=lambda kv: float(kv[0])):
            print(f"{p:>6s}{row['cells']:7d}{row['cells_passing_both']:7d}"
                  f"{row['max_byte_rate_gain_pct']:10.3f}"
                  f"{row['min_net_miss_worst_gating']:11.3e}"
                  f"{fmt_opt(row['best_bytes_per_row'], 'd'):>11s}"
                  f"{fmt_opt(row['best_gross_pct'], '.3f'):>12s}"
                  f"{fmt_opt(row['best_predicted_pct'], '.3f'):>13s}"
                  f"{fmt_opt(row['best_predicted_pct_incremental'], '.3f'):>11s}"
                  f"   {row['best_arm']}")
    out["byte_ladder"] = byte_ladder(out, stages)
    for stage_a, rows in out["byte_ladder"].items():
        print(f"\n=== byte ladder  ({out['by_stage_a'][stage_a]['label']})")
        print(f"{'B/row':>7s}{'cells':>7s}{'clear':>7s}{'maxGain%':>10s}"
              f"{'minNet':>11s}{'bestPredABS':>13s}{'bestPredF':>11s}"
              f"{'bestPredP':>11s}{'bestPredR':>11s}   best clearing arm")
        for size, row in sorted(rows.items(), key=lambda kv: int(kv[0])):
            print(f"{size:>7s}{row['cells']:7d}{row['cells_passing_both']:7d}"
                  f"{row['max_byte_rate_gain_pct']:10.3f}"
                  f"{row['min_net_miss_worst_gating']:11.3e}"
                  f"{fmt_opt(row['best_predicted_pct'], '.3f'):>13s}"
                  f"{fmt_opt(row['best_predicted_pct_incremental'], '.3f'):>11s}"
                  f"{fmt_opt(row['best_predicted_pct_pooled'], '.3f'):>11s}"
                  f"{fmt_opt(row['best_predicted_pct_raw_miss'], '.3f'):>11s}"
                  f"   {row['best_arm']}")
    # F3.3. The whitened grid is decided on its 252 exact twins, not on where
    # either family happens to land in the leaderboard.
    out["whitening_paired"] = whitening_paired(out)
    wp = out["whitening_paired"]
    print(f"\n=== F3.3 whitening, paired on {wp['paired_cells']} twin cells")
    print(f"{'field':34s}{'wins':>6s}{'ties':>6s}{'losses':>8s}"
          f"{'meanDelta':>13s}{'signTestP':>12s}")
    for field, r in wp["fields"].items():
        print(f"{field:34s}{r['whitened_wins']:6d}{r['ties']:6d}"
              f"{r['whitened_losses']:8d}"
              f"{fmt_opt(r['mean_delta_whitened_minus_plain'], '.4e'):>13s}"
              f"{fmt_opt(r['sign_test_p'], '.3e'):>12s}")
    print(f"  T0 verdict flips {wp['t0_verdict_flips']}, "
          f"T0b verdict flips {wp['t0b_verdict_flips']}")
    print(f"  best clearing plain    {wp['best_clearing_plain_arm']} "
          f"{fmt_opt(wp['best_clearing_plain_predicted_pct'], '.3f')}")
    print(f"  best clearing whitened {wp['best_clearing_whitened_arm']} "
          f"{fmt_opt(wp['best_clearing_whitened_predicted_pct'], '.3f')}")
    # F3.4. The held-out query energy at each rank, beside the empirical net
    # miss the same rank actually achieves. If captured energy predicted the
    # miss, the two columns would move together.
    out["spectrum_vs_miss"] = spectrum_vs_miss(out, stages)
    for stage_a, rows in out["spectrum_vs_miss"].items():
        print(f"\n=== spectrum vs miss  ({stage_a})")
        print(f"{'r':>6s}{'captured_beagle':>17s}{'captured_minc':>15s}"
              f"{'captured_bacon':>16s}{'bestNet':>11s}{'bestRecall':>12s}"
              f"{'arm':>34s}")
        for r, row in sorted(rows.items(), key=lambda kv: int(kv[0])):
            print(f"{r:>6s}{fmt_opt(row['captured_beagle']):>17s}"
                  f"{fmt_opt(row['captured_min_carriers']):>15s}"
                  f"{fmt_opt(row['captured_essays_bacon']):>16s}"
                  f"{fmt_opt(row['best_net_miss'], '.3e'):>11s}"
                  f"{fmt_opt(row['best_recall'], '.5f'):>12s}"
                  f"{str(row['best_arm']):>34s}")
    if args.out:
        Path(args.out).write_text(json.dumps(slim(out, args.top), indent=2))
        print(f"wrote {args.out}")
    if args.out_full:
        Path(args.out_full).write_text(json.dumps(out, indent=2))
        print(f"wrote {args.out_full}")


def slim(out: dict, top: int) -> dict:
    """Per-stratum detail for every cell is a large measurement artifact, so
    the committed file keeps it only for the cells the report cites."""
    keep = set()
    for stage, block in out["by_stage_a"].items():
        keep.update((block["best_arm"], block["cheapest_arm"]))
        arms = [c for c in out["cells"] if c["stage_a"] == stage]
        keep.update(c["arm"] for c in arms[:top])
    for block in ("spectrum_vs_miss", "byte_ladder", "probe_ladder"):
        for rows in out.get(block, {}).values():
            keep.update(row["best_arm"] for row in rows.values())
    trimmed = [c if c["arm"] in keep
               else {k: v for k, v in c.items() if k != "by_stratum"}
               for c in out["cells"]]
    return {**out, "cells": trimmed,
            "detail_retained_for_arms": sorted(a for a in keep if a)}


